"""Validation of the estimation engine by masking SYNTHETIC data with known true values.

For each synthetic facility-year (synth.random_facility), observations are removed by a masking scenario, the engine
assesses the data and proposes estimates, all proposals are approved, and the results are compared with the hidden
truth. The engine is run with raw (uncalibrated) prediction sds; calibration factors are applied afterwards, so that
the same experiments give the "before" and "after" coverage and so that the factors can be fitted on one set of
facilities (calibration) and evaluated on others (held-out test sets and other generator families).

These are synthetic results: they test the logic and the calibration of the intervals on data generated by our own
model, not performance on real industrial records.
"""
import json
import math
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import pandas as pd
from scipy.stats import norm

from . import synth
from .estimate import Ledger

ESTIMATED_STREAMS = ("production", "electricity", "natural_gas", "diesel_forklift", "steel_purchased")
SCENARIOS = {
    "random_1": "1 random month removed per stream",
    "random_3": "3 random (non-adjacent allowed) months removed per stream",
    "block_3": "3 consecutive summer months (Jun-Aug) removed per stream",
    "rate_25": "each month of each stream removed with probability 25%",
    "rate_40": "each month of each stream removed with probability 40%",
    "block_6": "6 consecutive months (Mar-Aug) removed per stream - the engine should refuse",
    "after_break": "break variants only: 1 random month at or after the operational change removed in each changed stream, "
                   "plus 1 random month in every other stream",
}
CAL_SCENARIOS = ("random_1", "random_3", "block_3", "rate_25", "rate_40")
NOMINAL = (0.50, 0.80, 0.90, 0.95, 0.99)


def _mask(truth, scenario, rng, year=2026, info=None):
    t = truth.copy()
    cur = t[t.period.str.startswith(str(year))]
    drop = []
    for s in ESTIMATED_STREAMS:
        g = cur[cur.stream == s].sort_values("period")
        idx = list(g.index)
        if scenario == "random_1":
            drop += list(rng.choice(idx, 1, replace=False))
        elif scenario == "random_3":
            drop += list(rng.choice(idx, 3, replace=False))
        elif scenario == "block_3":
            drop += idx[5:8]
        elif scenario == "block_6":
            drop += idx[2:8]
        elif scenario.startswith("rate_"):
            p = int(scenario.split("_")[1]) / 100
            drop += [i for i in idx if rng.uniform() < p]
        elif scenario == "after_break":
            if info and s in info["break_streams"]:
                post = [i for i in idx if g.at[i, "period"] >= info["break_month"]]
                drop += list(rng.choice(post, 1, replace=False))
            else:
                drop += list(rng.choice(idx, 1, replace=False))
    return t.drop(drop), set(drop)


def run_one(truth, scenario, rng, year=2026, detect_changes=True, info=None):
    raw, dropped = _mask(truth, scenario, rng, year, info)
    L = Ledger(raw, year, source_name=f"masked:{scenario}", detect_changes=detect_changes, calibrate=False)
    tv = truth[truth.period.str.startswith(str(year))].set_index(["period", "stream"])["value"]
    masked = {(truth.at[i, "period"], truth.at[i, "stream"]) for i in dropped}
    false_alarms = 0
    for _, r in L.table[(L.table.status == "outlier")].iterrows():
        if (r.period, r.stream) not in masked:
            L.decide(r.site, r.period, r.stream, "keep", "validation", "true value (false alarm)"); false_alarms += 1
    L.approve_all("validation")
    f = L.final()
    brk = info or {}
    cells = []
    for _, r in f[f.apply(lambda r: (r.period, r.stream) in masked, axis=1)].iterrows():
        true = float(tv[(r.period, r.stream)])
        cand = json.loads(r.candidates) if r.candidates else {}
        est_ok = not np.isnan(r.estimate)
        fb = r.fallback_estimate
        cells.append(dict(scenario=scenario, period=r.period, stream=r.stream, true=true,
                          estimated=bool(est_ok and r.decision == "approved"), refusal=r.refusal.split(":")[0] if r.refusal else "",
                          method=r.method, estimate=r.estimate, sd=r.sd,
                          rel_err=(r.estimate - true) / true if est_ok and true else np.nan,
                          z=(r.estimate - true) / r.sd if est_ok and r.sd > 0 else np.nan,
                          covered=(r.low95 <= true <= r.high95) if est_ok else np.nan,
                          change_warning="OPERATIONAL_CHANGE" in r.warning, between_warning="LEVEL_CHANGE" in r.warning,
                          production_anomaly="PRODUCTION_ANOMALY" in r.warning,
                          fallback_rel_err=(fb - true) / true if not np.isnan(fb) else np.nan,
                          after_break=bool(brk and r.stream in brk["break_streams"] and r.period >= brk["break_month"]),
                          **{f"err_{m}": (c["estimate"] - true) / true for m, c in cand.items() if true}))
    ann = []
    a = L.annual()
    for _, r in a.iterrows():
        if r.stream not in ESTIMATED_STREAMS:
            continue
        true_tot = float(tv[[(p, r.stream) for p in sorted({k[0] for k in tv.index})]].sum())
        measured = float(f[(f.stream == r.stream) & f.status.isin(["measured", "converted"])].value.sum())
        sds = f[(f.stream == r.stream) & f.final_label.str.startswith("estimated")].final_sd.values
        g = f[(f.stream == r.stream) & (f.decision != "")]
        row = dict(scenario=scenario, stream=r.stream, n_gaps=int(12 - r.n_measured), complete=bool(r.complete),
                   n_est=int(r.n_estimated), true_total=true_tot, naive_zero_err=(measured - true_tot) / true_tot,
                   change_warning=bool(g.warning.str.contains("OPERATIONAL_CHANGE").any()),
                   change_refusal=bool(g.refusal.str.startswith("OPERATIONAL_CHANGE").any()),
                   break_stream=bool(brk and r.stream in brk["break_streams"]))
        if r.complete and r.n_estimated:
            row.update(total=float(r.total), err_abs=float(r.total - true_tot), annual_err=(r.total - true_tot) / true_tot,
                       s1=float(sds.sum()), s2=float(np.square(sds).sum()))
        ann.append(row)
    ann.append(dict(scenario=scenario, stream="_false_outlier_flags", n_gaps=false_alarms, complete=True,
                    true_total=float(len(tv)), naive_zero_err=np.nan))
    return cells, ann


def _facility_job(args):
    seed, i, variant, scenarios, detect_changes = args
    rng = np.random.default_rng([seed, i])
    info = {}
    truth = synth.random_facility(rng, variant=variant, info=info)
    cells, ann = [], []
    for s in scenarios:
        c, a = run_one(truth, s, np.random.default_rng([seed, i, list(SCENARIOS).index(s)]), detect_changes=detect_changes,
                       info=info or None)
        for x in c + a:
            x.update(facility=i, variant=variant, **({"break_month": info.get("break_month"), "break_size": info.get("break_size")}
                                                     if info else {}))
        cells += c; ann += a
    return cells, ann


def study(n_facilities=150, seed=4404, scenarios=tuple(SCENARIOS)[:6], variant="base", detect_changes=True, workers=1):
    """Masking study on n synthetic facilities of one generator family. Facility i uses rng [seed, i], so the same
    facilities and masks are produced for any engine setting (paired before/after comparison)."""
    jobs = [(seed, i, variant, tuple(scenarios), detect_changes) for i in range(n_facilities)]
    if workers > 1:
        with ProcessPoolExecutor(workers) as ex:
            res = list(ex.map(_facility_job, jobs, chunksize=4))
    else:
        res = [_facility_job(j) for j in jobs]
    cells = [c for r in res for c in r[0]]; ann = [a for r in res for a in r[1]]
    return pd.DataFrame(cells), pd.DataFrame(ann)


# ------------------------------------------------------------------ calibration
def wilson(k, n, z=1.96):
    """Wilson score 95% interval for a proportion k/n."""
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def conformal_factor(z, level=0.95):
    """Split-conformal multiplier on the sd: the ceil((n+1)level)-th smallest |z| divided by the normal quantile."""
    a = np.sort(np.abs(np.asarray(z, float)[~np.isnan(z)]))
    n = len(a)
    k = min(int(math.ceil((n + 1) * level)), n)
    return float(a[k - 1] / norm.ppf(0.5 + level / 2)), n


def annual_sd(s1, s2, rho):
    return np.sqrt(np.maximum(s2 + rho * (s1 * s1 - s2), 0.0))


def rho_for_coverage(ann, cal, level=0.95):
    """Smallest common within-stream error correlation rho in [0, 1] whose annual intervals reach `level` coverage on
    the calibration stream-years with at least two estimated months (1 = linear sum, the previous rule)."""
    a = ann[ann.complete & (ann.n_est >= 2) & ann.err_abs.notna()]
    for rho in np.round(np.arange(0, 1.0001, 0.01), 2):
        cov = (np.abs(a.err_abs) <= 1.96 * cal * annual_sd(a.s1, a.s2, rho)).mean()
        if cov >= level:
            return float(rho), len(a)
    return 1.0, len(a)


def empirical_rho(cells, ann_keys=("facility", "scenario", "stream")):
    """Pooled within-stream-year correlation of standardised monthly errors (pairs of estimated months)."""
    e = cells[cells.estimated & cells.z.notna()]
    num = den = 0.0
    for _, g in e.groupby(list(ann_keys)):
        z = g.z.values
        if len(z) < 2:
            continue
        s = z.sum()
        num += s * s - np.square(z).sum()
        den += len(z) * (len(z) - 1)
    return float(num / den / max(np.square(e.z).mean(), 1e-12)) if den else np.nan


def calibrate(cells, ann, level=0.95):
    est = cells[cells.estimated & cells.z.notna()]
    q, n = conformal_factor(est.z.values, level)
    cal = max(1.0, q)            # never narrow the monthly intervals below the statistical (t-based) width
    rho, n_ann = rho_for_coverage(ann, cal, level)
    return dict(cal_monthly=cal, conformal_q=q, n_cells=n, rho_annual=rho, n_stream_years=n_ann,
                empirical_rho=empirical_rho(cells))


def coverage_rows(cells, ann, cal, rho, label):
    """Monthly and annual 95% coverage (with Wilson intervals) and mean relative half-width, by scenario and overall."""
    rows = []
    for scen in [None] + sorted(set(cells.scenario)):
        c = cells[cells.estimated & cells.z.notna()] if scen is None else cells[(cells.scenario == scen) & cells.estimated & cells.z.notna()]
        a = ann[ann.complete & ann.err_abs.notna()] if scen is None else ann[(ann.scenario == scen) & ann.complete & ann.err_abs.notna()]
        if not len(c):
            continue
        km = int((np.abs(c.z) <= 1.96 * cal).sum()); nm = len(c)
        sd_a = cal * annual_sd(a.s1, a.s2, rho)
        ka = int((np.abs(a.err_abs) <= 1.96 * sd_a).sum()); na = len(a)
        lo_m, hi_m = wilson(km, nm); lo_a, hi_a = wilson(ka, na)
        rows.append(dict(setting=label, scenario=scen or "all", monthly_n=nm, monthly_coverage=km / nm, monthly_ci_low=lo_m,
                         monthly_ci_high=hi_m, monthly_halfwidth=float((1.96 * cal * c.sd / c.true).mean()),
                         annual_n=na, annual_coverage=ka / na if na else np.nan, annual_ci_low=lo_a, annual_ci_high=hi_a,
                         annual_halfwidth=float((1.96 * sd_a / a.true_total).mean()) if na else np.nan))
    return rows


def reliability(cells, cal, label):
    c = cells[cells.estimated & cells.z.notna()]
    out = []
    for nom in NOMINAL:
        k = int((np.abs(c.z) <= norm.ppf(0.5 + nom / 2) * cal).sum())
        lo, hi = wilson(k, len(c))
        out.append(dict(setting=label, nominal=nom, empirical=k / len(c), ci_low=lo, ci_high=hi, n=len(c)))
    return out


# ------------------------------------------------------------------ summaries
def summarise(cells, ann, cal=1.0, rho=1.0):
    rows = []
    for s in SCENARIOS:
        c, a = cells[cells.scenario == s], ann[ann.scenario == s]
        if not len(c):
            continue
        fa = a[a.stream == "_false_outlier_flags"]; a = a[a.stream != "_false_outlier_flags"]
        est = c[c.estimated]
        ac = a[a.complete & a.err_abs.notna()] if "err_abs" in a else a.iloc[0:0]
        sd_a = cal * annual_sd(ac.s1, ac.s2, rho) if len(ac) else np.array([])
        rows.append(dict(
            scenario=s, description=SCENARIOS[s], gaps=len(c), refused_share=1 - len(est) / len(c),
            change_refusal_share=float((c.refusal == "OPERATIONAL_CHANGE").mean()),
            monthly_mape=float(est.rel_err.abs().mean()) if len(est) else np.nan,
            monthly_p95_abs_err=float(est.rel_err.abs().quantile(0.95)) if len(est) else np.nan,
            monthly_coverage95=float((np.abs(est.z) <= 1.96 * cal).mean()) if len(est) else np.nan,
            stream_years_complete=float(a.complete.mean()) if len(a) else np.nan,
            annual_mape=float(ac.annual_err.abs().mean()) if len(ac) else np.nan,
            annual_max_abs_err=float(ac.annual_err.abs().max()) if len(ac) else np.nan,
            annual_coverage95=float((np.abs(ac.err_abs) <= 1.96 * sd_a).mean()) if len(ac) else np.nan,
            false_outlier_flag_rate=float(fa.n_gaps.sum() / fa.true_total.sum()) if len(fa) else np.nan,
            naive_zero_annual_mape=float(a[a.n_gaps > 0].naive_zero_err.abs().mean()) if len(a) else np.nan))
    return pd.DataFrame(rows)


def by_stream(cells, cal=1.0):
    est = cells[cells.estimated]
    g = est.groupby("stream")
    return pd.DataFrame(dict(gaps_estimated=g.size(), mape=g.rel_err.apply(lambda x: x.abs().mean()),
                             coverage95=g.z.apply(lambda x: float((np.abs(x) <= 1.96 * cal).mean())),
                             main_method=g.method.agg(lambda x: x.value_counts().index[0]))).reset_index()


def by_method(cells):
    rows = []
    est = cells[cells.estimated]
    for col in [c for c in cells.columns if c.startswith("err_")]:
        x = est[col].dropna()
        rows.append(dict(method=col[4:], n=len(x), mape=float(x.abs().mean()), bias=float(x.mean())))
    sel = est.rel_err.dropna()
    rows.append(dict(method="selected (lowest LOO error)", n=len(sel), mape=float(sel.abs().mean()), bias=float(sel.mean())))
    return pd.DataFrame(rows)


def change_detection_summary(cells_new, ann_new, cells_old, label):
    """False alarms (no-break data) or detection / error effect (break data); old = engine without change detection."""
    a = ann_new[ann_new.stream != "_false_outlier_flags"]
    a = a[a.n_gaps > 0].astype({"change_warning": bool, "change_refusal": bool, "break_stream": bool})
    out = dict(dataset=label, stream_years_with_gaps=len(a),
               change_warning_rate=float(a.change_warning.mean()), change_refusal_rate=float(a.change_refusal.mean()))
    if "break_stream" in a and a.break_stream.any():
        b = a[a.break_stream]; nb = a[~a.break_stream]
        out.update(detection_rate_break_streams=float(b.change_warning.mean()),
                   false_warning_rate_other_streams=float(nb.change_warning.mean()))
        cn = cells_new[cells_new.after_break]; co = cells_old[cells_old.after_break]
        out.update(after_break_gaps=len(cn),
                   after_break_refused_new=float((~cn.estimated).mean()),
                   after_break_mape_old=float(co[co.estimated].rel_err.abs().mean()),
                   after_break_mape_new=float(cn[cn.estimated].rel_err.abs().mean()) if cn.estimated.any() else np.nan,
                   after_break_coverage_old=float(co[co.estimated].covered.astype(float).mean()),
                   after_break_coverage_new=float(cn[cn.estimated].covered.astype(float).mean()) if cn.estimated.any() else np.nan,
                   after_break_old_abs_err_gt_10pct=float((co[co.estimated].rel_err.abs() > 0.10).mean()),
                   after_break_new_abs_err_gt_10pct=float((cn[cn.estimated].rel_err.abs() > 0.10).mean()) if cn.estimated.any() else np.nan)
    return out


def detection_by_size(ann_new):
    a = ann_new[(ann_new.stream != "_false_outlier_flags") & (ann_new.n_gaps > 0)]
    a = a.astype({"change_warning": bool, "change_refusal": bool, "break_stream": bool})
    a = a[a.break_stream]
    bands = pd.cut(a.break_size.abs(), [0.0, 0.15, 0.25, 0.35, 0.45, 0.55], labels=["10%", "20%", "30%", "40%", "50%"])
    a = a.assign(abs_size=bands.astype(str))
    return a.groupby("abs_size").agg(stream_years=("change_warning", "size"), detected=("change_warning", "mean"),
                                     refused=("change_refusal", "mean")).reset_index()


