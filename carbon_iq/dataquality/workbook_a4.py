"""A4 Excel workbook: data-quality review with live formulas (synthetic demonstration data).

The Review sheet recomputes final values, annual totals and emissions from the reviewer's decisions. An unresolved gap
evaluates to #N/A and propagates to the annual total and the emissions: a missing value can never become zero.
Decision results (Monte Carlo) and the validation study come from Python and are shown as values (purple).
"""
import numpy as np
import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

from ..assumptions import P
from ..workbook import BOX, F_B, F_CALC, F_HDR, F_IN, F_PY, F_SUB, F_TITLE, FILL_HDR, FILL_KEY
from .estimate import (CAL_MONTHLY, CP_ALPHA, CP_MIN_SHIFT, MAX_GAP_RUN, MAX_REL_ERR, METHOD_TEXT, MIN_MEASURED, MIN_REGIME,
                       RHO_ANNUAL)
from .quality import ROBUST_Z, STREAMS

EF = {"electricity": "ef_grid", "natural_gas": "ef_gas", "diesel_forklift": "ef_diesel", "diesel_genset": "ef_diesel",
      "steel_purchased": "ef_steel_incumbent", "freight": "ef_freight"}
FILL_EST = PatternFill("solid", fgColor="FCE4D6")
FILL_GAP = PatternFill("solid", fgColor="F4CCCC")


def _hdr(ws, row, cols, widths=None):
    for j, c in enumerate(cols, 1):
        x = ws.cell(row, j, c); x.font = F_HDR; x.fill = FILL_HDR; x.alignment = Alignment(wrap_text=True, vertical="center")
        if widths:
            ws.column_dimensions[get_column_letter(j)].width = widths[j - 1]


def _val(x):
    if x is None:
        return None
    if isinstance(x, (dict, list, tuple)):
        import json
        return json.dumps(x, default=str)
    if isinstance(x, (float, np.floating)) and np.isnan(x):
        return None
    if isinstance(x, (np.bool_,)):
        return bool(x)
    if isinstance(x, np.generic):
        return x.item()
    return x


def _table(ws, row, df, font=F_PY, widths=None):
    _hdr(ws, row, list(df.columns), widths)
    for i, r in enumerate(df.itertuples(index=False), row + 1):
        for j, v in enumerate(r, 1):
            c = ws.cell(i, j, _val(v)); c.font = font; c.border = BOX
            if isinstance(v, float):
                c.number_format = "0.000" if abs(v) < 10 else "#,##0.0"
    return row + len(df) + 2


def build(ledger, truth, decisions, validation, path, extra=()):
    wb = Workbook()
    ws = wb.active; ws.title = "Read me"
    ws["A1"] = "CARBON IQ - A4 missing-data review"; ws["A1"].font = F_TITLE
    lines = [
        "ALL DATA IN THIS WORKBOOK ARE SYNTHETIC (generated by carbon_iq/dataquality/synth.py). They demonstrate and test the "
        "method; they are not real industrial observations and the error statistics are not evidence of real-world accuracy.",
        "Raw data: the uploaded records, unchanged (sha256 " + ledger.raw_hash + ").",
        "Review: one row per site-month-stream. Blue cells (column N, decision) are the reviewer's inputs; everything to the right "
        "is a live formula. Set a decision to 'rejected' to see the gap become #N/A in the annual total and the emissions.",
        "Annual & emissions: totals from the Review sheet, compared with the assumption register (model v1.2).",
        "Decisions: Monte Carlo results computed by Python (values, purple).  Validation: masking study on synthetic facilities.",
        f"Rules: robust z-score threshold {ROBUST_Z} (Iglewicz & Hoaglin); at least {MIN_MEASURED} measured months; no estimate "
        f"for runs of more than {MAX_GAP_RUN} consecutive missing months; no estimate if the back-test error exceeds "
        f"{MAX_REL_ERR:.0%} of the monthly mean. Estimation is rule-based and statistical; no machine-learning model is used.",
        f"Prediction intervals: leave-one-out back-test RMSE x sqrt(1+1/n), widened by t(0.975, n-1)/1.96 and by the calibration "
        f"factor {CAL_MONTHLY:.4f} (split-conformal on synthetic calibration facilities). Annual totals combine monthly errors with "
        f"a within-stream correlation rho = {RHO_ANNUAL} (calibrated; rho = 1 reproduces the earlier, wider linear sum). Calibration "
        "sheet: empirical coverage on held-out synthetic sets - evidence for the synthetic generator family only.",
        f"Operational change: a permutation test (p < {CP_ALPHA}) for a shift of at least {CP_MIN_SHIFT:.0%} in the quantity each "
        f"method assumes constant; after a change only same-regime months are used, and estimation is refused with fewer than "
        f"{MIN_REGIME} such months or when the gap sits at the change point (a reviewer may override; the label records it).",
    ] + [f"Method '{k}': {v}" for k, v in METHOD_TEXT.items()] + [
        "Colour key: blue = input, black = formula, purple = value computed in Python, orange fill = estimated, red fill = gap."]
    for i, t in enumerate(lines, 3):
        ws.cell(i, 1, t).alignment = Alignment(wrap_text=True, vertical="top")
    ws.column_dimensions["A"].width = 130

    # raw
    wr = wb.create_sheet("Raw data")
    raw = ledger.raw.copy()
    _table(wr, 1, raw.astype(object).where(raw.notna(), None), font=F_CALC, widths=[10, 10, 9, 16, 14, 7, 40, 30])

    # review
    rv = wb.create_sheet("Review")
    cols = ["Site", "Period", "Stream", "Unit", "Status", "Issues", "Observed value", "Method", "Estimate", "sd", "Low 95%",
            "High 95%", "Refusal", "Decision (input)", "Final value", "Final sd", "Label", "Unresolved", "Final (numeric)",
            "Estimated?", "Synthetic truth", "Estimate error", "Warning", "Fallback estimate (override only)", "Fallback sd",
            "Final sd squared"]
    _hdr(rv, 1, cols, [10, 9, 16, 6, 13, 36, 13, 15, 12, 10, 11, 11, 30, 14, 13, 10, 14, 9, 13, 9, 13, 10, 40, 13, 10, 10])
    rv.freeze_panes = "A2"
    dv = DataValidation(type="list", formula1='"pending,approved,rejected,kept,confirmed_zero,change_overridden"', allow_blank=True)
    rv.add_data_validation(dv)
    tv = truth.set_index(["period", "stream"]).value
    t = ledger.table
    for i, r in enumerate(t.itertuples(index=False), 2):
        vals = [r.site, r.period, r.stream, r.unit, r.status, "; ".join(r.issues), _val(r.value), r.method or None, _val(r.estimate),
                _val(r.sd)]
        for j, v in enumerate(vals, 1):
            c = rv.cell(i, j, v); c.font = F_CALC; c.border = BOX
        has_est = _val(r.estimate) is not None
        if has_est:                                          # interval formulas only where an estimate exists
            rv.cell(i, 11, f"=MAX(0,I{i}-1.96*J{i})")
            rv.cell(i, 12, f"=I{i}+1.96*J{i}")
        rv.cell(i, 13, r.refusal or None)
        d = rv.cell(i, 14, r.decision or None); d.font = F_IN; d.fill = FILL_KEY
        if r.decision:
            dv.add(d)
        meas = f'OR(E{i}="measured",E{i}="converted")'
        rv.cell(i, 15, f'=IF({meas},G{i},IF(AND(N{i}="approved",I{i}<>""),I{i},IF(AND(N{i}="change_overridden",X{i}<>""),X{i},'
                       f'IF(N{i}="kept",G{i},IF(N{i}="confirmed_zero",0,NA())))))')
        rv.cell(i, 16, f'=IF(AND(NOT({meas}),N{i}="approved",I{i}<>""),J{i},IF(AND(NOT({meas}),N{i}="change_overridden",X{i}<>""),Y{i},0))')
        rv.cell(i, 17, f'=IF({meas},E{i},IF(ISNA(O{i}),"UNRESOLVED",IF(N{i}="approved","estimated",N{i})))')
        rv.cell(i, 18, f"=IF(ISNA(O{i}),1,0)")
        rv.cell(i, 19, f"=IF(R{i}=1,0,O{i})")
        rv.cell(i, 20, f'=IF(AND(NOT({meas}),OR(AND(N{i}="approved",I{i}<>""),AND(N{i}="change_overridden",X{i}<>""))),1,0)')
        rv.cell(i, 23, r.warning or None)
        if _val(r.fallback_estimate) is not None:
            rv.cell(i, 24, float(r.fallback_estimate)).number_format = "#,##0.00"
            rv.cell(i, 25, float(r.fallback_sd)).number_format = "#,##0.00"
        rv.cell(i, 26, f"=P{i}^2").number_format = "#,##0.00"
        rv.cell(i, 21, float(tv[(r.period, r.stream)])).font = F_PY
        if has_est:
            rv.cell(i, 22, f"=I{i}/U{i}-1").number_format = "0.0%"
        for j in (7, 9, 10, 11, 12, 15, 16, 19, 21):
            rv.cell(i, j).number_format = "#,##0.00"
        for j in range(1, 27):
            rv.cell(i, j).border = BOX
            if r.decision and j <= 13:
                rv.cell(i, j).fill = FILL_GAP if r.status != "outlier" else FILL_EST
    last = len(t) + 1
    rng = lambda col: f"Review!${col}$2:${col}${last}"  # noqa: E731

    # annual and emissions
    an = wb.create_sheet("Annual & emissions")
    an["A1"] = "Annual totals and emissions from the reviewed data"; an["A1"].font = F_TITLE
    an["A2"] = "Live formulas on the Review sheet. #N/A = a gap is unresolved (missing data are never counted as zero)."; an["A2"].font = F_SUB
    an["A3"] = "Within-stream error correlation rho (calibrated; 1 = linear sum)"; an["A3"].font = F_B
    c = an["F3"]; c.value = RHO_ANNUAL; c.font = F_IN; c.fill = FILL_KEY
    hdr = ["Stream", "Unit", "Measured months", "Estimated months", "Unresolved months", "Annual total", "sd of estimated part",
           "Register (v1.2)", "Difference", "Emission factor", "Emissions (t)", "±95% from estimation (t)", "Register emissions (t)"]
    _hdr(an, 4, hdr, [20, 7, 10, 10, 11, 14, 13, 14, 10, 12, 13, 14, 14])
    reg = {s: c["register"] for s, c in STREAMS.items()}
    reg["production"] = "production_t"
    for i, (s, cfg) in enumerate(STREAMS.items(), 5):
        an.cell(i, 1, s); an.cell(i, 2, cfg["unit"])
        an.cell(i, 3, f'=COUNTIFS({rng("C")},A{i},{rng("E")},"measured")+COUNTIFS({rng("C")},A{i},{rng("E")},"converted")')
        an.cell(i, 4, f'=SUMIFS({rng("T")},{rng("C")},A{i})')
        an.cell(i, 5, f'=SUMIFS({rng("R")},{rng("C")},A{i})')
        an.cell(i, 6, f'=IF(E{i}>0,NA(),SUMIFS({rng("S")},{rng("C")},A{i}))').number_format = "#,##0.0"
        an.cell(i, 7, f'=SQRT(MAX(0,SUMIFS({rng("Z")},{rng("C")},A{i})+$F$3*(SUMIFS({rng("P")},{rng("C")},A{i})^2'
                      f'-SUMIFS({rng("Z")},{rng("C")},A{i}))))').number_format = "#,##0.0"
        if reg.get(s):
            c = an.cell(i, 8, P[reg[s]].value); c.font = F_IN; c.number_format = "#,##0"
            an.cell(i, 9, f"=F{i}/H{i}-1").number_format = "0.00%"
        if s in EF:
            c = an.cell(i, 10, P[EF[s]].value); c.font = F_IN; c.number_format = "0.00000"
            an.cell(i, 11, f"=F{i}*J{i}").number_format = "#,##0.0"
            an.cell(i, 12, f"=1.96*G{i}*J{i}").number_format = "#,##0.0"
            an.cell(i, 13, f"=H{i}*J{i}").number_format = "#,##0.0"
        for j in range(1, 14):
            an.cell(i, j).border = BOX
    tr = 5 + len(STREAMS)
    an.cell(tr, 1, "Total (streams with factors)").font = F_B
    an.cell(tr, 11, f"=SUM(K5:K{tr - 1})").number_format = "#,##0.0"
    an.cell(tr, 12, f"=SUM(L5:L{tr - 1})").number_format = "#,##0.0"
    an.cell(tr, 13, f"=SUM(M5:M{tr - 1})").number_format = "#,##0.0"
    an.cell(tr + 1, 1, "Difference from register emissions").font = F_B
    an.cell(tr + 1, 11, f"=K{tr}-M{tr}").number_format = "#,##0.0"
    an.cell(tr + 3, 1, "sd of the estimated part = sqrt(sum sd^2 + rho x ((sum sd)^2 - sum sd^2)); rho from the calibration study. "
            "The total row adds stream ranges linearly (conservative). Emission-factor uncertainty is handled in the main model.").font = F_SUB

    # decisions
    de = wb.create_sheet("Decisions")
    de["A1"] = "Effect of data quality on the investment decision (Python, 20,000 scenarios, seed 20261024)"; de["A1"].font = F_TITLE
    de["A2"] = "Synthetic demonstration. Choices flagged unstable are listed on the Stability sheet; see the report."; de["A2"].font = F_SUB
    keep = ["case", "description", "status", "D1", "D1_npv", "D2", "D3", "D4", "scope12", "target_t", "p_target[A+B]", "p_budget[A+B]",
            "p_target[A+C+D]", "p_target[A+B+C]", "min_budget", "detail"]
    d = decisions[[c for c in keep if c in decisions.columns]]
    _table(de, 4, d, widths=[6, 50, 10, 8, 12, 8, 8, 13, 10, 10, 11, 11, 11, 11, 13, 60])

    # validation
    va = wb.create_sheet("Validation")
    va["A1"] = "Masking validation on synthetic facilities (known truth)"; va["A1"].font = F_TITLE
    va["A2"] = "Tests the logic and the interval calibration on data from our own generator; NOT evidence of real-world accuracy."; va["A2"].font = F_SUB
    row = 4
    for title, df in validation:
        va.cell(row, 1, title).font = F_B
        row = _table(va, row + 1, df)
    for j, w in enumerate([22, 28, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10, 10], 1):
        va.column_dimensions[get_column_letter(j)].width = w

    for name, title, tables in extra:
        xs = wb.create_sheet(name)
        xs["A1"] = title; xs["A1"].font = F_TITLE
        xs["A2"] = "SYNTHETIC data; values computed by Python (purple)."; xs["A2"].font = F_SUB
        row = 4
        for sub, df in tables:
            xs.cell(row, 1, sub).font = F_B
            row = _table(xs, row + 1, df.reset_index(drop=True))
        for j in range(1, 30):
            xs.column_dimensions[get_column_letter(j)].width = 14
        xs.column_dimensions["A"].width = 26; xs.column_dimensions["B"].width = 30

    ev = wb.create_sheet("Lineage events")
    _table(ev, 1, pd.DataFrame(ledger.events), font=F_CALC, widths=[22, 14, 18, 90])
    wb.calculation.fullCalcOnLoad = True
    wb.save(path)
    return path
